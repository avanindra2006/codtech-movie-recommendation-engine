const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');

(async()=>{
  const root=path.resolve(__dirname,'..');
  const screenshots=path.join(root,'docs/screenshots');
  fs.mkdirSync(screenshots,{recursive:true});
  const browser=await chromium.launch({headless:true,...(process.env.CINEMATCH_BROWSER?{executablePath:process.env.CINEMATCH_BROWSER}:{})});
  const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const page=await context.newPage();
  const errors=[],checks=[];
  page.on('pageerror',error=>errors.push(error.message));
  const base=(process.env.CINEMATCH_URL||'http://127.0.0.1:8000').replace(/\/$/,'');
  const shelf=title=>page.locator(`.movie-shelf[aria-label="${title}"]`);
  const waitHome=()=>shelf('Movies you might like').locator('.movie-card').first().waitFor();
  await page.goto(base+'/#/',{waitUntil:'networkidle'});
  await waitHome();
  assert.deepEqual((await page.locator('.shelf-heading h2').allTextContents()).slice(0,3),['Movies you might like','Saved movies','Watch again']);
  assert.equal(await page.locator('.watched-editor').count(),0);
  assert.equal(await shelf('Movies you might like').locator('.shelf-cell').count(),10);
  assert.equal(await shelf('Movies you might like').locator('.movie-row-track > *').count(),11);
  checks.push('Home has the requested row order, ten movie previews plus See more, and no history editor');
  await page.getByRole('button',{name:'Scroll Movies you might like right',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.movie-row-track').scrollLeft>0);
  checks.push('Home rows scroll horizontally with arrow controls');
  const firstTen=await shelf('Movies you might like').locator('.movie-card h3').allTextContents();
  await page.getByRole('link',{name:'See more Movies you might like',exact:true}).click();
  await page.locator('.collection-grid .movie-card').nth(23).waitFor();
  assert(page.url().endsWith('#/collection/recommended'));
  assert.deepEqual((await page.locator('.collection-grid h3').allTextContents()).slice(0,10),firstTen);
  await page.getByRole('button',{name:'Load more movies',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.collection-grid .movie-card').length===48);
  const ids=await page.locator('.collection-grid .movie-card').evaluateAll(nodes=>nodes.map(node=>node.dataset.movieId));
  assert.equal(new Set(ids).size,48);
  checks.push('See more opens a matching collection; Load more expands it without duplicates');
  await page.getByRole('link',{name:'Watched movies',exact:true}).click();
  await page.getByRole('button',{name:'try a sci-fi profile',exact:true}).click();
  await page.getByRole('heading',{name:'3 watched movies',exact:true}).waitFor();
  await page.getByRole('textbox',{name:'Search watched movies',exact:true}).fill('Arrival');
  await page.getByRole('button',{name:/Arrival \(2016\)/}).click();
  await page.getByRole('heading',{name:'4 watched movies',exact:true}).waitFor();
  await page.getByRole('button',{name:'Remove Arrival (2016) from watched movies',exact:true}).click();
  await page.getByRole('heading',{name:'3 watched movies',exact:true}).waitFor();
  await page.getByRole('button',{name:'Rate Interstellar (2014) 1 stars',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Rate Interstellar (2014) 1 stars',exact:true}).getAttribute('aria-pressed'),'true');
  await page.screenshot({path:path.join(screenshots,'watched-page.jpg'),fullPage:true});
  checks.push('Watched page supports search, adding/removing films and rating changes');
  await page.getByRole('link',{name:'Home',exact:true}).click();await waitHome();
  assert.equal(await shelf('Watch again').locator('.movie-card').count(),2);
  assert.equal(await page.locator('.genre-shelves-caption span').textContent(),'From your most-watched genres');
  assert.equal((await page.locator('.shelf-heading h2').allTextContents())[3],'Sci-Fi movies');
  checks.push('Watch again excludes low ratings and empty favorite genres infer rows from watched counts');
  const savedTitle=await shelf('Movies you might like').locator('.movie-card h3').first().textContent();
  await shelf('Movies you might like').locator('.save-button').first().click();
  await page.getByRole('link',{name:'See more Saved movies',exact:true}).click();
  assert.equal(await page.locator('.collection-grid .movie-card').count(),1);
  assert.equal(await page.locator('.collection-grid h3').textContent(),savedTitle);
  await page.getByRole('link',{name:'Home',exact:true}).click();await waitHome();
  await page.getByRole('link',{name:'See more Watch again',exact:true}).click();
  assert.equal(await page.locator('.collection-grid .movie-card').count(),2);
  checks.push('Saved and Watch again See more cards open their own full lists');
  await page.getByRole('link',{name:'Home',exact:true}).click();await waitHome();
  await page.getByRole('link',{name:'See more Sci-Fi movies',exact:true}).click();
  await page.locator('.collection-grid .movie-card').nth(23).waitFor();
  assert((await page.locator('.collection-grid .genre-line').allTextContents()).every(text=>text.includes('Sci-Fi')));
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Sci-Fi movies',exact:true}).waitFor();
  await page.screenshot({path:path.join(screenshots,'genre-collection.jpg'),fullPage:true});
  checks.push('Genre See more retains the genre and survives page reload');
  await page.getByRole('link',{name:'Favorite genres',exact:true}).click();
  await page.getByRole('button',{name:'Favorite genre: Comedy',exact:true}).click();
  await page.getByRole('link',{name:'Home',exact:true}).click();await waitHome();
  assert.deepEqual(await page.locator('.shelf-heading h2').allTextContents(),['Movies you might like','Saved movies','Watch again','Comedy movies']);
  checks.push('Explicit favorite genres take precedence over watched-genre rows');
  await page.screenshot({path:path.join(screenshots,'home-rows-desktop.jpg'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.equal(await shelf('Movies you might like').locator('.movie-row-track').evaluate(node=>node.scrollWidth>node.clientWidth),true);
  checks.push('Desktop keeps the page within the viewport while each movie row scrolls sideways');
  assert.equal(errors.length,0);
  checks.push('No uncaught browser JavaScript errors');
  fs.writeFileSync(path.join(root,'reports/browser-checks.json'),JSON.stringify({date:new Date().toISOString().slice(0,10),checks,errors},null,2));
  console.log(JSON.stringify({passed:checks.length,checks,errors},null,2));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
