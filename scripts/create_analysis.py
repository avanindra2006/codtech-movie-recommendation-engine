"""Create real analysis charts and a sample response from the bundled dataset/model."""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from cinematch.data import read_data
from cinematch.model import Recommender

ROOT = Path(__file__).resolve().parents[1]


def main():
    output = ROOT / "reports/figures"
    output.mkdir(parents=True, exist_ok=True)
    movies, ratings, cleaning = read_data(ROOT / "data/movielens")
    report = json.loads((ROOT / "reports/evaluation.json").read_text())
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "axes.facecolor": "#f8f9f4", "figure.facecolor": "#f8f9f4",
                         "axes.labelcolor": "#42513a", "text.color": "#283624"})
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.7), layout="constrained")
    counts = ratings.rating.value_counts().sort_index()
    axes[0].bar(counts.index, counts.values, width=.36, color="#859e5c")
    axes[0].set(xlabel="Rating (stars)", ylabel="Number of ratings", title="Observed rating distribution")
    genre_counts = movies.genres.str.split("|").explode().value_counts().head(12).sort_values()
    axes[1].barh(genre_counts.index, genre_counts.values, color="#c5d798")
    axes[1].set(xlabel="Movies (multi-label)", title="Most represented genres")
    fig.suptitle("CineMatch / Dataset profile", fontsize=17, fontweight="bold")
    fig.savefig(output / "dataset_profile.png", dpi=180)
    plt.close(fig)
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.8), layout="constrained")
    methods = list(report["test"])
    colors = ["#b8bfad", "#97b894", "#738d73", "#c1da73"]
    for ax, metric, title in zip(axes, ["ndcg", "recall"], ["NDCG@10", "Recall@10"]):
        values = [report["test"][mode][metric] for mode in methods]
        bars = ax.bar(methods, values, color=colors, width=.65)
        ax.bar_label(bars, fmt="%.4f", padding=5, fontsize=10)
        ax.set(title=title, ylim=(0, max(values)*1.25), ylabel="Macro average over eligible test viewers")
    fig.suptitle("CineMatch / Held-out ranking evaluation", fontsize=17, fontweight="bold")
    fig.savefig(output / "ranking_comparison.png", dpi=180)
    plt.close(fig)
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5), layout="constrained")
    user_counts = ratings.groupby("userId").size()
    axes[0].hist(user_counts, bins=30, color="#7f9c72", edgecolor="#f8f9f4")
    axes[0].set(xlabel="Ratings per viewer", ylabel="Viewers", title="Unequal activity across viewers")
    dates = np.array([report["time_boundaries"][key] for key in
                      ["train_max", "validation_min", "validation_max", "test_min"]])
    axes[1].bar(["Train", "Validation", "Test"], list(report["split_sizes"].values()),
                color=["#839f75", "#c0d27b", "#d8bf88"])
    axes[1].set(ylabel="Number of ratings", title="Strict global time windows")
    assert dates[0] < dates[1] <= dates[2] < dates[3]
    fig.suptitle("CineMatch / Activity and experiment split", fontsize=17, fontweight="bold")
    fig.savefig(output / "activity_and_splits.png", dpi=180)
    plt.close(fig)
    model = Recommender.load(ROOT / "artifacts/model")
    example = {"request": {"ratings": [{"movieId": 2571, "rating": 5},
                                         {"movieId": 79132, "rating": 5},
                                         {"movieId": 109487, "rating": 5}]},
               "recommendations": model.recommend({2571:5, 79132:5, 109487:5}, k=12)}
    (ROOT / "reports/sample_recommendations.json").write_text(json.dumps(example, indent=2), encoding="utf-8")
    (ROOT / "reports/cleaning.json").write_text(json.dumps(cleaning, indent=2), encoding="utf-8")
    lines = ["# Recorded experiment", "", "Generated by `cinematch evaluate`; no estimated metrics.", "",
             "| Method | NDCG@10 | Recall@10 | Precision@10 | Hit rate@10 | Coverage |", "|---|---:|---:|---:|---:|---:|"]
    for mode, m in report["test"].items():
        lines.append(f"| {mode} | {m['ndcg']:.4f} | {m['recall']:.4f} | {m['precision']:.4f} | {m['hit_rate']:.4f} | {m['catalog_coverage']:.2%} |")
    hybrid = report["test"]["hybrid"]
    lines.extend(["", f"Evaluated **{hybrid['evaluated_users']}** warm viewers; **{hybrid['excluded_users']}** of **{hybrid['heldout_users']}** held-out viewers were ineligible.",
                  "", f"Validation-selected collaborative share: **{report['selected_alpha']}** (remaining personalized share uses content; popularity contributes 10% overall).",
                  "", "## Interpretation", "", *[f"- {s}" for s in report["limitations"]],
                  "", "NDCG rewards relevant films near the top. Recall measures the fraction of future liked films retrieved. Precision divides hits by 10. Coverage is the fraction of the full catalog recommended at least once. Novelty and genre diversity are available in evaluation.json.",
                  "", "The baseline is Bayesian quality plus rating activity, rather than a neural model. The hybrid is not assumed to outperform every baseline. Read the measured table above.",
                  "", "See `docs/METHODOLOGY.md` for split rules, candidate definition, and formulas."])
    (ROOT / "reports/RESULTS.md").write_text("\n".join(lines)+"\n", encoding="utf-8")
    print("Analysis charts, sample response, cleaning report, and RESULTS.md created.")


if __name__ == "__main__":
    main()
